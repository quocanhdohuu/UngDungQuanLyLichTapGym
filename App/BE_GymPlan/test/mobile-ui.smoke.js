    await page.getByText("Mục tiêu RPE: Chưa thiết lập", { exact: true }).waitFor();
    await page.getByRole("button", { name: "Xác nhận hiệp", exact: true }).first().click();
    await page.getByRole("button", { name: "✓ Đã lưu", exact: true }).waitFor();
