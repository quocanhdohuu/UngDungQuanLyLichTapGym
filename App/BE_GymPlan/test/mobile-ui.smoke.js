    await page.getByRole("button", { name: "Lọc nhóm cơ Bụng", exact: true }).click();
    await page.getByText("Không tìm thấy bài tập phù hợp", { exact: true }).waitFor();
    await page.getByRole("button", { name: "Lọc nhóm cơ Ngực", exact: true }).click();
    await page.getByText(fixture + " Exercise", { exact: true }).waitFor();
    await page.screenshot({ path: path.join(screenshots, "library.png"), fullPage: true });
    await page.getByText(fixture + " Exercise", { exact: true }).click();
    await page.waitForURL(/\/exercises\/\d+/);
    await page.getByText("Kỷ lục của bạn", { exact: true }).waitFor();
    await page.getByText("25 KG", { exact: true }).waitFor();
    for (let step = 1; step <= 4; step++) await page.getByText("BƯỚC " + step, { exact: true }).waitFor();
    await page.getByText("Lỗi thường gặp", { exact: true }).waitFor();
    await page.screenshot({ path: path.join(screenshots, "exercise-guide.png"), fullPage: true });
    await page.goto((process.env.GYM_WEB_URL || "http://localhost:8082") + "/plans", { waitUntil: "domcontentloaded" });
    await page.getByText("Tạo lịch mới", { exact: true }).click();
    await page.getByLabel("Tên chương trình", { exact: true }).fill(fixture + " Custom");
    await page.getByRole("button", { name: "+ Thêm bài tập", exact: true }).click();
    await page.getByLabel("Tìm bài tập", { exact: true }).fill(fixture);
